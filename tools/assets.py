# Native CGA overrides allow different artwork at 16x8. Otherwise halve the
# full icon, keeping outline/body/highlight overlap priority unchanged.
for name, rows in icons.items():
    override = root/'assets/icons/cga'/f'{name}.txt'
    native = override.exists()
    if native:
        rows = override.read_text().splitlines()
        assert len(rows) == 8 and all(len(row) == 16 for row in rows), name
        assert all(c in 'Xo+.' for row in rows for c in row), name
    masks = []
    for channel in range(3):
        for y in range(8):
            if native:
                bits = int(''.join('1' if c == 'Xo+'[channel] else '0' for c in rows[y]), 2)
                masks.extend([bits >> 8, bits & 255])
                continue
            merged = []
            for c in 'Xo+':
                merged.append(int(''.join('1' if rows[y*2][x] == c or rows[y*2+1][x] == c else '0' for x in range(16)), 2))
            bits = merged[channel]
            if channel: bits &= ~merged[0]
            if channel == 2: bits &= ~merged[1]
            masks.extend([bits >> 8, bits & 255])
    result += table('cga_' + name, masks)
result = result.replace('#endif\n', '')
result += 'static const unsigned char *cga_icon_masks[] = { ' + ', '.join('cga_'+n for n in icons) + ' };\n'
# VGA sprites: opaque mask then four EGA-index bitplanes, 32 bytes each.
# Keep 16x16 dimensions and the same row geometry as the monochrome icons.
for name in icon_order:
    image = quickmenu_icon(name.title())
    pixels = list(image.getdata())
    data = []
    for plane in range(-1,4):
        for y in range(16):
            bits = 0
            for x in range(16):
                pixel = pixels[y*16+x]
                assert pixel[3] in (0,255)
                color = palette.index(pixel[:3]) if pixel[3] else 0
                bit = bool(pixel[3]) if plane == -1 else bool((color >> plane) & 1)
                bits = (bits << 1) | bit
            data.extend((bits >> 8,bits & 255))
    result += table('vga_'+name,data)
result += 'static const unsigned char *vga_icon_sprites[] = { ' + ', '.join('vga_'+n for n in icons) + ' };\n#endif\n'
