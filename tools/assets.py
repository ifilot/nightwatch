"""Compile vendored Spleen fonts and attributed pixel icons to DOS tables.

Generated fonts live in a separate immutable segment, outside the near heap.
VGA uses color planes and transparency; EGA/CGA retain their native masks.
"""
from pathlib import Path
import re
from icons_v130 import quickmenu_icon
