root = Path(__file__).resolve().parents[1]

# Convert BDF Unicode glyphs into a 256-entry CP437 table. Each scanline is
# one byte, high bit at the left, even for fonts narrower than eight pixels.
def font(size):
    text = (root / 'assets/fonts' / f'spleen-{size}.bdf').read_text()
    width, height = map(int,size.split('x'))
    glyphs = {}
    for glyph in re.findall(r'STARTCHAR .*?\n(.*?)ENDCHAR',text,re.S):
        encoding = int(re.search(r'^ENCODING (\d+)',glyph,re.M)[1])
        rows = [int(s,16) for s in glyph.split('BITMAP\n')[1].strip().splitlines()]
        assert len(rows) == height
        glyphs[encoding] = rows
    # Use light box drawing only when the requested double-line glyph is absent.
    fallback = {0x2550:0x2500,0x2551:0x2502,0x2554:0x250c,0x2557:0x2510,
                0x255a:0x2514,0x255d:0x2518,0x2560:0x251c,0x2563:0x2524,
                0x2566:0x252c,0x2569:0x2534,0x256c:0x253c}
    result = []
    for code in range(256):
        unicode = ord(bytes([code]).decode('cp437'))
        result += glyphs.get(unicode,glyphs.get(fallback.get(unicode),glyphs[63]))
    return result

# Emit immutable C byte tables; icons stay near, while font bytes use FONTDATA.
def table(name,data,far=False):
    rows=['    '+', '.join(f'0x{n:02x}' for n in data[i:i+16])+',' for i in range(0,len(data),16)]
    return f'static const unsigned char {"far " if far else ""}{name}[{len(data)}] = {{\n'+ '\n'.join(rows)+'\n};\n'

